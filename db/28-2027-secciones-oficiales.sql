SELECT count(*) AS secciones,
       count(id_distrito_local)   AS con_distrito_local,
       count(id_distrito_federal) AS con_distrito_federal
  FROM sirve.seccion s
  JOIN sirve.proceso_electoral p ON p.id = s.id_proceso
 WHERE p.anio = 2027;

SELECT e.clave, count(ce.id_casilla) AS casillas
  FROM sirve.eleccion e
  JOIN sirve.proceso_electoral p ON p.id = e.id_proceso AND p.anio = 2027
  LEFT JOIN sirve.casilla_eleccion ce ON ce.id_eleccion = e.id
 GROUP BY e.clave, e.orden
 ORDER BY e.orden;

